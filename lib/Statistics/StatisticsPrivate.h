 #ifndef STATISTICS_PRIVATE_H
 #define STATISTICS_PRIVATE_H
 
 #include <Arduino.h>
 
 /*=============================================================================
     Runtime Data
 =============================================================================*/
 
 struct StatisticsRuntime
 {
     /*---------------------------------------------------------------------
         Mean
     ---------------------------------------------------------------------*/
 
     float sum;
 
     /*---------------------------------------------------------------------
         RMS
     ---------------------------------------------------------------------*/
 
     float squareSum;
 
     /*---------------------------------------------------------------------
         Peak Detection
     ---------------------------------------------------------------------*/
 
     float peak;
 
     /*---------------------------------------------------------------------
         Window Counter
     ---------------------------------------------------------------------*/
 
     uint16_t sampleCount;
 
     /*---------------------------------------------------------------------
         Sample Rate
     ---------------------------------------------------------------------*/
 
     uint32_t previousTimestamp;
 
     float sampleRate;
 
     /*---------------------------------------------------------------------
         Constructor
     ---------------------------------------------------------------------*/
 
     StatisticsRuntime()
         :
         sum(0.0f),
         squareSum(0.0f),
         peak(0.0f),
         sampleCount(0U),
         previousTimestamp(0UL),
         sampleRate(0.0f)
     {
     }
 };
 
 #endif // STATISTICS_PRIVATE_H