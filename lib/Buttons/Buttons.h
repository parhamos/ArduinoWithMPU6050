#ifndef BUTTONS_H
#define BUTTONS_H

#include <Arduino.h>

#include "ButtonsPrivate.h"

/*=============================================================================
    Buttons
=============================================================================*/

class Buttons
{
public:

    /*-------------------------------------------------------------------------
        Construction
    -------------------------------------------------------------------------*/

    Buttons();

    /*-------------------------------------------------------------------------
        Initialization
    -------------------------------------------------------------------------*/

    bool begin();

    /*-------------------------------------------------------------------------
        Update
    -------------------------------------------------------------------------*/

    bool update();

    /*-------------------------------------------------------------------------
        Event
    -------------------------------------------------------------------------*/

    bool getEvent(ButtonEvent& event);

    /*-------------------------------------------------------------------------
        Clear Event
    -------------------------------------------------------------------------*/

    void clearEvent();

private:

    /*-------------------------------------------------------------------------
        Individual Button Update
    -------------------------------------------------------------------------*/

    void updateButton(ButtonRuntime& button,
                      uint8_t pin,
                      ButtonId id);

private:

    /*-------------------------------------------------------------------------
        Button Runtime Objects
    -------------------------------------------------------------------------*/

    ButtonRuntime next_;

    ButtonRuntime previous_;

    ButtonRuntime ok_;

    ButtonRuntime f1_;

    ButtonRuntime f2_;

    ButtonRuntime f3_;

private:

    /*-------------------------------------------------------------------------
        Current Event
    -------------------------------------------------------------------------*/

    ButtonEvent event_;
};

/*=============================================================================
    Global Instance
=============================================================================*/

extern Buttons buttons;

#endif // BUTTONS_H